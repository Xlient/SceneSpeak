import { useId, useState } from "react";
import { speakWithBrowser, voiceTags } from "@scenespeak/core/audio/browser-voice";
import { VOICE_HELP, detectPlatform } from "@scenespeak/core/audio/voice-help";
import type { VoiceChoice } from "@scenespeak/core/audio/voice-preference";
import { useBrowserVoices, useVoiceChoice } from "./use-voices";

const TAG_LABEL = { premium: "clear", online: "online", novelty: "novelty" } as const;
const SAMPLE: Record<string, string> = { es: "¡Hola! Encantado de conocerte." };

const toValue = (choice: VoiceChoice) => (choice.kind === "device" ? `device:${choice.voiceName}` : choice.kind);
const fromValue = (value: string): VoiceChoice =>
  value.startsWith("device:") ? { kind: "device", voiceName: value.slice("device:".length) } : value === "cloud" ? { kind: "cloud" } : { kind: "auto" };

export interface VoicePickerProps {
  language: string;
  /** False while the cloud voice isn't wired up; the option stays visible but explains why. */
  cloudAvailable: boolean;
}

export const VoicePicker = ({ language, cloudAvailable }: VoicePickerProps) => {
  const voices = useBrowserVoices(language);
  const [choice, setChoice] = useVoiceChoice(language);
  const [helpOpen, setHelpOpen] = useState(false);
  const selectId = useId();
  const help = VOICE_HELP[detectPlatform(typeof navigator === "undefined" ? "" : navigator.userAgent)];
  const sample = SAMPLE[language.split("-")[0] ?? language] ?? "Hello!";
  const noClearVoice = !voices.some((v) => voiceTags(v).includes("premium"));

  return (
    <div className="voice-picker">
      <label htmlFor={selectId}>🔊 Voice</label>
      <div className="voice-picker-row">
        <select id={selectId} value={toValue(choice)} onChange={(event) => setChoice(fromValue(event.target.value))}>
          <option value="auto">Auto (best on this device)</option>
          <option value="cloud">AI voice, cloud{cloudAvailable ? "" : " (coming soon)"}</option>
          {voices.length > 0 && (
            <optgroup label="Voices on this device">
              {voices.map((voice) => {
                const tags = voiceTags(voice).map((tag) => TAG_LABEL[tag]);
                return (
                  <option key={voice.name} value={`device:${voice.name}`}>
                    {voice.name} · {voice.lang}
                    {tags.length > 0 ? ` (${tags.join(", ")})` : ""}
                  </option>
                );
              })}
            </optgroup>
          )}
        </select>
        <button
          type="button"
          className="secondary small"
          disabled={choice.kind === "cloud"}
          onClick={() => speakWithBrowser(sample, language, undefined, choice.kind === "device" ? choice.voiceName : undefined)}
        >
          Test
        </button>
      </div>
      {choice.kind === "cloud" && !cloudAvailable && (
        <p className="audio-note">The AI voice isn't connected yet, so your device's best voice plays for now.</p>
      )}
      {choice.kind === "cloud" && cloudAvailable && (
        <p className="audio-note">
          <span className="badge cloud">Cloud</span> Each line is voiced once by Gemini, then cached on this device.
        </p>
      )}
      <button type="button" className="link-button" aria-expanded={helpOpen} onClick={() => setHelpOpen((open) => !open)}>
        {noClearVoice ? "Voices sound robotic? Get a clearer one" : "Get more voices"}
      </button>
      {helpOpen && (
        <div className="voice-help">
          <p>
            <strong>Free and offline:</strong> install a clearer voice on your device. {help.title}:
          </p>
          <ol>
            {help.steps.map((step) => (
              <li key={step}>{step}</li>
            ))}
          </ol>
          <p>
            <strong>No install:</strong> choose <em>AI voice, cloud</em> above for natural speech generated by Gemini.
          </p>
        </div>
      )}
    </div>
  );
};
