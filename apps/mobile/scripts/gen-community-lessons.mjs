// Metro has no import.meta.glob, so the mobile app bundles community lessons through a generated map.
// Run after adding a lesson: node scripts/gen-community-lessons.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const LESSONS = join(here, "../../../packages/core/lessons");
const OUT = join(here, "../src/lessons/community.generated.ts");

const files = readdirSync(LESSONS, { recursive: true, encoding: "utf8" })
  .filter((file) => file.endsWith(".json"))
  .sort();

const lines = files.map((file) => `  ${JSON.stringify(`lessons/${file}`)}: require(${JSON.stringify(relative(dirname(OUT), join(LESSONS, file)))}),`);
writeFileSync(
  OUT,
  `// Generated by scripts/gen-community-lessons.mjs. Do not edit.\nexport const COMMUNITY_FILES: Readonly<Record<string, unknown>> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`bundled ${files.length} community lessons`);
