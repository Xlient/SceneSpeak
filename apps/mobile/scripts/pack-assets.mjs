// Packs the web app's .gltf + .bin + .png props into self-contained .glb files and writes the
// require() map Metro needs (native can't resolve a glTF's external files through the bundler).
// Run: node scripts/pack-assets.mjs
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const PUBLIC = join(here, "../../web/public");
const OUT = join(here, "../assets/models");
const MAP_FILE = join(here, "../src/scene/asset-map.generated.ts");
const SOURCE_DIRS = ["assets/kaykit-restaurant"];

const pad4 = (buffer, fill) => {
  const extra = (4 - (buffer.length % 4)) % 4;
  return extra === 0 ? buffer : Buffer.concat([buffer, Buffer.alloc(extra, fill)]);
};

const pack = (gltfPath) => {
  const dir = dirname(gltfPath);
  const gltf = JSON.parse(readFileSync(gltfPath, "utf8"));
  if ((gltf.buffers ?? []).length !== 1) throw new Error(`${gltfPath}: expected one buffer`);
  const chunks = [pad4(readFileSync(join(dir, gltf.buffers[0].uri)), 0)];
  let offset = chunks[0].length;
  gltf.bufferViews ??= [];
  for (const image of gltf.images ?? []) {
    if (!image.uri) continue;
    const bytes = readFileSync(join(dir, decodeURIComponent(image.uri)));
    gltf.bufferViews.push({ buffer: 0, byteOffset: offset, byteLength: bytes.length });
    image.bufferView = gltf.bufferViews.length - 1;
    image.mimeType ??= "image/png";
    delete image.uri;
    const padded = pad4(bytes, 0);
    chunks.push(padded);
    offset += padded.length;
  }
  const bin = Buffer.concat(chunks);
  gltf.buffers = [{ byteLength: bin.length }];
  const json = pad4(Buffer.from(JSON.stringify(gltf)), 0x20);
  const header = Buffer.alloc(12);
  header.writeUInt32LE(0x46546c67, 0); // "glTF"
  header.writeUInt32LE(2, 4);
  header.writeUInt32LE(12 + 8 + json.length + 8 + bin.length, 8);
  const chunkHeader = (length, type) => {
    const b = Buffer.alloc(8);
    b.writeUInt32LE(length, 0);
    b.writeUInt32LE(type, 4);
    return b;
  };
  return Buffer.concat([header, chunkHeader(json.length, 0x4e4f534a), json, chunkHeader(bin.length, 0x004e4942), bin]);
};

const entries = [];
for (const sourceDir of SOURCE_DIRS) {
  const outDir = join(OUT, basename(sourceDir));
  mkdirSync(outDir, { recursive: true });
  for (const file of readdirSync(join(PUBLIC, sourceDir)).filter((f) => f.endsWith(".gltf")).sort()) {
    const glb = join(outDir, file.replace(/\.gltf$/, ".glb"));
    writeFileSync(glb, pack(join(PUBLIC, sourceDir, file)));
    entries.push([`/${sourceDir}/${file}`, relative(dirname(MAP_FILE), glb)]);
  }
}

const lines = entries.map(([url, path]) => `  ${JSON.stringify(url)}: require(${JSON.stringify(path)}),`);
mkdirSync(dirname(MAP_FILE), { recursive: true });
writeFileSync(
  MAP_FILE,
  `// Generated by scripts/pack-assets.mjs. Do not edit.\n// Catalog URL → Metro asset module.\nexport const ASSET_MODULES: Readonly<Record<string, number>> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`packed ${entries.length} models`);
